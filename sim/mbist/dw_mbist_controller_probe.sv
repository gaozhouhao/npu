// Isolated probe of the DC-supplied controller interface, not part of npu_top.
module dw_mbist_controller_probe (
    input  logic clk,
    input  logic rst_n,
    input  logic mbrun,
    input  logic [15:0] mode_reg_in,
    input  logic mode_reg_si,
    input  logic shift_dr,
    input  logic parallel_dr,
    input  logic segment_active,
    input  logic mem_fail_n,
    input  logic mr_ctrl_sel_rst,
    input  logic mr_marchlr_rst,
    input  logic mr_marchc_rst,
    input  logic mr_mats_rst,
    input  logic mr_retn_rst,
    input  logic mr_debug_mode_rst,
    input  logic mr_mem_sel_stat_rst,
    output logic mode_reg_so,
    output logic [15:0] mode_reg_out,
    output logic atpg_1,
    output logic bist_mode,
    output logic [4:0] segment_descr,
    output logic segment_en,
    output logic [3:0] port_no,
    output logic continue_test,
    output logic cont_pause_on_error,
    output logic load_parallel_pattern,
    output logic load_serial_pattern,
    output logic serial_pattern_out
);
    DW_mbist_ctrl #(
        .num_mem(1),
        .num_ports_0(1),
        .data_width_0(64),
        .registered_io_0(2)
    ) u_controller (
        .bist_clk(clk),
        .bist_clk_t(clk),
        .rst_n_a(rst_n),
        .rst_t_n_a(rst_n),
        .mbrun(mbrun),
        .mode_reg_in(mode_reg_in),
        .mode_reg_si(mode_reg_si),
        .shift_dr(shift_dr),
        .parallel_dr(parallel_dr),
        .segment_active(segment_active),
        .mem_fail_n(mem_fail_n),
        .mr_ctrl_sel_rst(mr_ctrl_sel_rst),
        .mr_marchlr_rst(mr_marchlr_rst),
        .mr_marchc_rst(mr_marchc_rst),
        .mr_mats_rst(mr_mats_rst),
        .mr_retn_rst(mr_retn_rst),
        .mr_debug_mode_rst(mr_debug_mode_rst),
        .mr_mem_sel_stat_rst(mr_mem_sel_stat_rst),
        .mode_reg_so(mode_reg_so),
        .mode_reg_out(mode_reg_out),
        .atpg_1(atpg_1),
        .bist_mode(bist_mode),
        .segment_descr(segment_descr),
        .segment_en(segment_en),
        .port_no(port_no),
        .continue_test(continue_test),
        .cont_pause_on_error(cont_pause_on_error),
        .load_parallel_pattern(load_parallel_pattern),
        .load_serial_pattern(load_serial_pattern),
        .serial_pattern_out(serial_pattern_out)
    );
endmodule
